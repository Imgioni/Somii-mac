// Writes src/plugin/FxDefs.h from ui/fxdefs.mjs (the FX rack's single source of truth).
// Run from the repository root:  node tools/gen-fx-header.mjs
import fs from 'node:fs';
import { FX, NP, DIV_BEATS, toNorm } from '../ui/fxdefs.mjs';

const f = (x) => { const s = String(Math.fround(x)); return (s.includes('.') || s.includes('e') ? s : s + '.0') + 'f'; };
const ident = (id) => id[0].toUpperCase() + id.slice(1);
let rows = '';
for (const fx of [{ id: 'none', name: 'NONE', params: [], mix: 100 }, ...FX]) {
  const cells = [];
  for (let i = 1; i <= NP; i++) {
    const q = fx.params.find((x) => x.p === 'p' + i);
    if (!q) { cells.push('{ 0.0f, 1.0f, 0, 0, 0.0f }'); continue; }
    if (q.steps) cells.push('{ 0.0f, ' + f(q.steps.length - 1) + ', 2, ' + q.steps.length + ', ' + f(toNorm(q, q.def)) + ' }');
    else cells.push('{ ' + f(q.lo) + ', ' + f(q.hi) + ', ' + (q.curve === 'log' ? 1 : 0) + ', 0, ' + f(toNorm(q, q.def)) + ' }');
  }
  rows += '    { // ' + fx.name + '\n      ' + cells.join(',\n      ') + ' },\n';
}
const out = `#pragma once
// GENERATED by tools/gen-fx-header.mjs from ui/fxdefs.mjs - do not edit by hand.

#include <cmath>
#include <cstdint>

namespace fxdefs
{
enum Type { None = 0, ${FX.map((x, i) => ident(x.id) + ' = ' + (i + 1)).join(', ')}, kNumTypes };
constexpr int kNP = ${NP};

struct Param { float lo, hi; uint8_t curve; uint8_t steps; float def; };   // curve 0 lin, 1 log, 2 stepped; def normalised

inline constexpr const char* kTypeNames[kNumTypes] = { "NONE", ${FX.map((x) => '"' + x.name + '"').join(', ')} };
inline constexpr float kDefaultMix[kNumTypes] = { 1.0f, ${FX.map((x) => f(x.mix / 100)).join(', ')} };
inline constexpr float kDivBeats[] = { ${DIV_BEATS.map(f).join(', ')} };
constexpr int kNumDivs = ${DIV_BEATS.length};

inline constexpr Param kParams[kNumTypes][kNP] = {
${rows}};

// Real value of parameter index i (0-based: p1 = 0) for normalised n.
inline float value (int type, int i, float n) noexcept
{
    const auto& q = kParams[type][i];
    if (q.curve == 2) return std::floor (n * q.hi + 0.5f);
    if (q.curve == 1) return q.lo * std::pow (q.hi / q.lo, n);
    return q.lo + (q.hi - q.lo) * n;
}
} // namespace fxdefs
`;
fs.writeFileSync(new URL('../src/plugin/FxDefs.h', import.meta.url), out);
console.log('wrote src/plugin/FxDefs.h');
